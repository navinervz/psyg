#!/usr/bin/env bash
#
# پشتیبان‌گیری از داده‌ی حیاتی سایت.
#
# روی سرور اجرا می‌شود. برای اجرای خودکار روزانه:
#   crontab -e
#   0 3 * * * bash /opt/psyg/scripts/backup.sh >> /var/log/psyg-backup.log 2>&1
#
# ─────────────────────────────────────────────────────────────────────
# چرا «bash» ابتدای خط cron لازم است
# ─────────────────────────────────────────────────────────────────────
# نسخه‌ی اول این خط، اسکریپت را مستقیم صدا می‌زد. دو شب اجرا شد و هر دو
# بار این را در لاگ نوشت:
#
#   /bin/sh: 1: /opt/psyg/scripts/backup.sh: Permission denied
#
# چون بسته‌ی دیپلوی روی ویندوز ساخته می‌شود و زیپ ویندوزی بیت اجرا را
# نگه نمی‌دارد، فایل بعد از هر unzip بدون مجوز اجرا می‌نشیند.
#
# `chmod +x` مشکل را حل می‌کرد ولی دیپلوی بعدی دوباره خرابش می‌کرد.
# صدا زدن با `bash` اصلاً به آن بیت نیاز ندارد، پس از این کلاس خطا
# مصون است.
#
# درسِ گران‌تر این بود که خرابی هیچ نشانه‌ای بیرون از آن فایل لاگ
# نداشت: خط cron سرجایش بود، اجرای دستی کار می‌کرد، و آرشیوهای دستی
# در پوشه بودند. همه‌چیز شبیه یک سیستم سالم به نظر می‌رسید.
#
# ─────────────────────────────────────────────────────────────────────
# چرا این لازم است
# ─────────────────────────────────────────────────────────────────────
# چهار فایل روی والیوم داکر زندگی می‌کنند و هیچ‌کدام جای دیگری کپی
# ندارند:
#
#   catalog.json      قیمت‌ها و تاریخچه‌شان
#   articles.json     مقاله‌های تولیدشده
#   admin.json        محصولات پنهان‌شده و دستی
#   subscribers.json  نشانی ایمیل آدم‌های واقعی
#
# تاریخچه‌ی قیمت از همه مهم‌تر است چون **قابل بازسازی نیست**. افیلیو
# فقط قیمت امروز را می‌دهد؛ قیمت سه هفته پیش هیچ‌جا نیست جز همین فایل.
# از دست دادنش یعنی نمودارها و هشدارها — یعنی کل ارزش سایت — از صفر
# شروع می‌کنند.
#
# فهرست مشترکان هم قابل بازسازی نیست و برخلاف بقیه، متعلق به ماست ولی
# داده‌ی دیگران است.

set -euo pipefail

APP_DIR="/opt/psyg"
BACKUP_DIR="/opt/psyg-backups"
CONTAINER="psyg-web"
KEEP_DAYS=30

mkdir -p "$BACKUP_DIR"

stamp=$(date +%Y-%m-%d_%H%M)
target="$BACKUP_DIR/psyg-data-$stamp.tar.gz"

# داده داخل کانتینر است، پس از همان‌جا خوانده می‌شود. خواندن مستقیم از
# مسیر والیوم روی هاست هم ممکن است ولی به جزئیات داکر وابسته می‌شود.
if ! docker exec "$CONTAINER" test -d /data 2>/dev/null; then
  echo "[$(date)] کانتینر بالا نیست یا /data ندارد — پشتیبان گرفته نشد"
  exit 1
fi

docker exec "$CONTAINER" tar czf - -C /data . > "$target"

size=$(stat -c%s "$target")

# یک آرشیو خالی یعنی چیزی اشتباه رفته. نگه داشتنش بدتر از نداشتنش است،
# چون بعداً فکر می‌کنی پشتیبان داری در حالی که نداری.
if [ "$size" -lt 1000 ]; then
  echo "[$(date)] آرشیو مشکوک است ($size بایت) — حذف شد"
  rm -f "$target"
  exit 1
fi

echo "[$(date)] پشتیبان گرفته شد: $target ($((size / 1024)) کیلوبایت)"

# نگه داشتن یک ماه. بیشتر از این فضا می‌گیرد بدون اینکه به کسی کمک کند؛
# اگر خرابی داده یک ماه دیده نشود، احتمالاً هیچ‌وقت دیده نمی‌شود.
deleted=$(find "$BACKUP_DIR" -name "psyg-data-*.tar.gz" -mtime +$KEEP_DAYS -delete -print | wc -l)
if [ "$deleted" -gt 0 ]; then
  echo "[$(date)] $deleted پشتیبان قدیمی پاک شد"
fi

# نمایش وضعیت فعلی تا با یک نگاه معلوم باشد سیستم زنده است
count=$(find "$BACKUP_DIR" -name "psyg-data-*.tar.gz" | wc -l)
total=$(du -sh "$BACKUP_DIR" | cut -f1)
echo "[$(date)] مجموع: $count پشتیبان، $total"
