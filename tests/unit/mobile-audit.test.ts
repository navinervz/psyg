import test, { describe } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..", "..");
const read = (p: string) => readFileSync(join(ROOT, p), "utf8");

function code(src: string): string {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/(^|[^:])\/\/.*$/gm, "$1");
}

/*
  ─────────────────────────────────────────────────────────────────────
  چرا این فایل وجود دارد
  ─────────────────────────────────────────────────────────────────────
  یک ممیزی بیرونی هشت ایراد موبایل فهرست کرد. خودِ فایل اعتراف می‌کرد
  که مرورگر را در عرض موبایل باز نکرده و شش مورد از هشت مورد را
  «استنباطی / نیازمند تأیید» علامت زده بود.

  اندازه‌گیری روی سایت زنده نشان داد کدام‌ها واقعی‌اند:

    ✓ هدف لمسی «مشاهده همه» → ۱۶ تا ۱۸ پیکسل بود (واقعی)
    ✗ اسکرول افقی صفحه      → وجود نداشت
    ✗ بریدن عنوان محصول     → `line-clamp-2` از قبل بود
    ✗ چیدمان فرم خبرنامه    → روی موبایل از قبل عمودی بود
    ✗ نیاز به منوی همبرگری  → عمداً حذف شده بود، نه از قلم افتاده

  و دو چیزی که ممیزی ندید ولی در اسکرین‌شات گوشی پیدا بودند:
  محو شدن سرچ‌بار از `opacity: 0`، و فضای خالی زیر بنر.

  درس: «ممیزی گفته» با «اندازه گرفتم» یکی نیست.
*/

describe("هدف لمسی: ناحیه‌ی لمس از ناحیه‌ی متن بزرگ‌تر است", () => {
  /*
    این لینک‌ها متن کوچک دارند و بزرگ کردن خودشان با پدینگ، هم‌ترازی
    تیتر سکشن را به‌هم می‌زند. راه‌حل `after` است — ناحیه‌ی لمسی کشیده
    می‌شود بدون اینکه چیزی در چیدمان جابه‌جا شود.

    اگر کسی این را بردارد، هیچ‌چیز خراب به‌نظر نمی‌رسد؛ فقط زدن لینک
    روی گوشی سخت می‌شود. یعنی دقیقاً همان نوع باگی که تست لازم دارد.
  */
  const cases: [string, string][] = [
    ["src/components/ui/SectionHeader.tsx", "«مشاهده همه» در همه‌ی سکشن‌ها"],
    ["src/components/mobile/MobileCategoryRail.tsx", "«مشاهده همه» نوار دسته‌بندی"],
    ["src/components/mobile/MobileHero.tsx", "نقطه‌های بنر"],
  ];

  for (const [path, label] of cases) {
    test(label, () => {
      const src = code(read(path));
      assert.match(
        src,
        /after:absolute[\s\S]{0,140}after:content-\[''\]/,
        `${label}: ناحیه‌ی لمسی گسترش‌یافته حذف شده`,
      );
    });
  }
});

describe("چیزهای حیاتی بالای صفحه از نامرئی شروع نمی‌شوند", () => {
  test("سرچ‌بار هیچ انیمیشن ورودی ندارد", () => {
    /*
      این قاعده دو بار سفت‌تر شد، هر بار بعد از یک باگ واقعی روی گوشی:

      ۱. `opacity: 0` با `duration: 1` → فیلد بیش از یک ثانیه بعد از
         هیدریت نامرئی بود و حفره‌ای بالای صفحه می‌ماند.
      ۲. بعد از حذف opacity، `y: 18` ماند → همان ۱۸ پیکسل، فیلد را در
         فاصله‌ی ۱۲ پیکسلی‌اش با بنر زیرش فرو می‌برد. کاربر نوشت
         «فیلد سرچ چسبیده به ویجت پایینی».

      نسخه‌ی اول این تست فقط `opacity` را ممنوع می‌کرد و مورد دوم از
      کنارش رد شد. حالا کل حرکت ممنوع است.

      `gsap.to` برای درخشش دکمه اشکالی ندارد: بعد از نشستن صفحه اجرا
      می‌شود و چیدمان را تکان نمی‌دهد.
    */
    const src = code(read("src/components/hero/AiSearchBar.tsx"));

    assert.ok(
      !/gsap\.from\s*\(\s*scope\.current/.test(src),
      "مهم‌ترین المان بالای صفحه نباید موقع ورود جابه‌جا یا محو شود",
    );
  });
});

describe("نوار دسته‌بندی نام‌ها را نمی‌برد", () => {
  const src = code(read("src/components/mobile/MobileCategoryRail.tsx"));
  const labels = JSON.parse(read("src/data/categories.json")) as {
    label: string;
  }[];

  test("بلندترین نام در عرض کاشی جا می‌شود", () => {
    /*
      حساب سرانگشتی: فونت ۱۰ پیکسلی فارسی حدود ۵.۵ پیکسل به‌ازای هر
      کاراکتر می‌گیرد. کاشی ۸۸ پیکسلی منهای پدینگ ۱۲ یعنی ۷۶ پیکسل
      مفید در هر سطر، و دو سطر مجاز است.

      این تست دقیق نیست — رندر واقعی فونت را نمی‌داند. کاری که می‌کند
      این است که اگر کسی روزی دسته‌ای با نام خیلی بلند اضافه کند یا
      کاشی را باریک‌تر کند، صدایش دربیاید.
    */
    const width = Number(src.match(/w-\[(\d+)px\]/)?.[1]);
    assert.ok(width, "عرض کاشی پیدا نشد");

    const longest = labels.reduce((a, b) =>
      a.label.length > b.label.length ? a : b,
    );
    const needed = longest.label.length * 5.5;
    const available = (width - 12) * 2;

    assert.ok(
      needed <= available,
      `«${longest.label}» حدود ${Math.round(needed)} پیکسل می‌خواهد ولی ${available} پیکسل جا هست`,
    );
  });

  test("دو سطر مجاز است و کاشی‌ها هم‌ارتفاع می‌مانند", () => {
    assert.ok(
      src.includes("line-clamp-2"),
      "یک سطر برای نام‌های بلند کافی نیست",
    );
    assert.ok(
      src.includes("min-h-["),
      "بدون حداقل ارتفاع، کاشی یک‌سطری کوتاه‌تر می‌شود و نوار ناهموار",
    );
  });
});

describe("بنر موبایل زیر خودش فضای خالی نمی‌گذارد", () => {
  const src = code(read("src/components/mobile/MobileHero.tsx"));

  test("هر دو کارت کل ارتفاع نوار را پر می‌کنند", () => {
    /*
      در فلکس افقی، ارتفاع نوار برابر بلندترین اسلاید است. بدون
      `h-full` کارتِ کوتاه‌تر در جعبه‌ی بلند شناور می‌ماند و زیرش
      شکاف می‌افتد — چیزی که در اسکرین‌شات بین بنر و نقطه‌ها دیده شد.
    */
    const cards = src.match(/card-surface[^"]*/g) ?? [];
    assert.ok(cards.length >= 2, "کارت‌های اسلاید پیدا نشدند");

    for (const card of cards) {
      assert.ok(
        card.includes("h-full"),
        `یک اسلاید بدون h-full مانده: ${card.slice(0, 60)}`,
      );
    }
  });
});
