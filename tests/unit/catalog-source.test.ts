import test, { describe } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..", "..");
const read = (p: string) => readFileSync(join(ROOT, p), "utf8");

/*
  ─────────────────────────────────────────────────────────────────────
  چرا این فایل وجود دارد
  ─────────────────────────────────────────────────────────────────────
  کاربر روی `psygstore.shop/product/sony-wh-1000xm5` به ۴۰۴ خورد.

  آن slug هیچ‌وقت در کاتالوگ زنده نبوده — یکی از محصولات *نمونه* است که
  برای توسعه و تست نوشته شده‌اند. گشتیم: هیچ صفحه‌ای از سایت به چنین
  آدرسی لینک نمی‌داد.

  یعنی سایت لحظه‌ای داده‌ی نمونه سرو کرده. کافی بود خواندن
  `/data/catalog.json` یک بار شکست بخورد — و `loadProducts` بی‌صدا ۵۱
  محصول جعلی با قیمت جعلی، تاریخچه‌ی جعلی و لینک خریدی که به جایی
  نمی‌رود برمی‌گرداند. برای کاربر هیچ فرقی با محصول واقعی نداشتند.

  همان الگوی همیشگی: کار می‌کرد، خطا نمی‌داد، و چیز اشتباهی نشان می‌داد.
*/

describe("روی سرور، داده‌ی نمونه سرو نمی‌شود", () => {
  const data = read("src/lib/data.ts");

  test("پرچم الزام کاتالوگ زنده وجود دارد", () => {
    assert.match(
      data,
      /PSYG_REQUIRE_CATALOG/,
      "بدون این پرچم، شکست خواندن کاتالوگ به داده‌ی نمونه برمی‌گردد",
    );
  });

  test("در آن حالت خالی برمی‌گردد، نه نمونه", () => {
    /*
      صفحه‌ی خالی با حالت «چیزی پیدا نشد» صادق است. پنجاه‌ویک محصول
      جعلی نیست.
    */
    assert.match(
      data,
      /REQUIRE_LIVE_CATALOG[\s\S]{0,400}value = \[\]/,
      "وقتی کاتالوگ زنده الزامی است، فالبک باید خالی باشد",
    );
  });

  test("پرچم روی سرور واقعاً ست شده", () => {
    /*
      کد درست بدون تنظیمِ درست، همان باگ است. این تست همان چیزی را
      می‌سنجد که سرور از آن می‌خواند.
    */
    const compose = read("docker-compose.yml");
    assert.match(
      compose,
      /PSYG_REQUIRE_CATALOG:\s*"1"/,
      "پرچم در docker-compose ست نشده — کد سخت‌گیر است ولی سرور نمی‌داند",
    );
  });

  test("توسعه و تست همچنان داده‌ی نمونه دارند", () => {
    /*
      اگر فالبک را کامل حذف می‌کردیم، `npm run dev` و کل تست‌های e2e
      روی سایت خالی اجرا می‌شدند. پرچم صریح، هر دو دنیا را نگه می‌دارد.
    */
    assert.match(
      data,
      /lastSource = "seed"[\s\S]{0,120}SEED_PRODUCTS/,
      "بدون پرچم باید همچنان به داده‌ی نمونه برگردد",
    );
  });
});

describe("منبع داده قابل دیدن است", () => {
  test("سلامت سایت منبع را گزارش می‌کند", () => {
    /*
      قبلاً `problems` فقط با دیدن الگوی شناسه‌ها («dk-») حدس می‌زد که
      داده نمونه است — یک تشخیص غیرمستقیم که به نام‌گذاری وابسته بود.

      حالا خودِ تصمیم گزارش می‌شود.
    */
    const health = read("src/app/api/health/route.ts");
    assert.match(health, /catalogSource/, "منبع کاتالوگ باید در سلامت بیاید");
    assert.match(
      health,
      /serving_seed_data/,
      "داده‌ی نمونه روی سرور باید مشکل حساب شود",
    );
    assert.match(
      health,
      /catalog_missing/,
      "کاتالوگ خوانده‌نشده باید مشکل حساب شود",
    );
  });

  test("تابعش از بیرون قابل صدا زدن است", () => {
    const data = read("src/lib/data.ts");
    assert.match(data, /export function catalogSource/);
    /*
      باید خودش `loadProducts` را صدا بزند، وگرنه اگر پیش از اولین
      خواندن صدا زده شود مقدار اولیه را برمی‌گرداند — یعنی «seed» را
      گزارش می‌کند در حالی که هنوز چیزی خوانده نشده.
    */
    assert.match(
      data,
      /export function catalogSource[\s\S]{0,300}loadProducts\(\)/,
      "باید مطمئن شود لااقل یک بار خوانده شده",
    );
  });
});
