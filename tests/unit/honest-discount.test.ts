import test, { describe } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { toProduct } from "@/lib/affilio";

const ROOT = join(import.meta.dirname, "..", "..");
const read = (p: string) => readFileSync(join(ROOT, p), "utf8");

/*
  ─────────────────────────────────────────────────────────────────────
  چرا این فایل وجود دارد
  ─────────────────────────────────────────────────────────────────────
  روی صفحه‌ی اصلی این جمله نشسته بود:

    «بیشترین افت این هفته: تبلت ۱۰ اینچ یومیو مدل S24 Ultra 5G ظرفیت
     ۵۱۲ گیگابایت رم ۸ گیگابایت — ۹۷٪ کمتر»

  قیمت آن تبلت روی صفحه‌ی محصول ۳۱۰٬۰۰۰ تومان بود.

  دو چیز هم‌زمان غلط بود:

  ۱. سقف «تخفیف باورپذیر» به `discount_percent` افیلیو نگاه می‌کرد، در
     حالی که آن فیلد با `price` و `price_discount` همان رکورد نمی‌خواند.
     نگهبان، چیزی غیر از آنچه محافظت می‌کرد را می‌سنجید.

  ۲. `previousPrice` از `raw.price` پر می‌شد — یعنی قیمت پیش از تخفیفِ
     فروشگاه. سایت آن را «افت این هفته» می‌نامید، درباره‌ی محصولی که
     فقط یک بار دیده بود.

  برای سایتی که تنها سرمایه‌اش اعتماد به قیمت‌هاست، این بدترین نوع باگ
  است: هیچ خطایی تولید نمی‌کند و فقط دروغ می‌گوید.
*/

const SOURCE = {
  id: "w-1",
  store: "digikala" as const,
  category: "tablet" as const,
  label: "تبلت",
};

function raw(over: Record<string, unknown> = {}) {
  return {
    uid: "11111111-2222-3333-4444-555555555555",
    name: "تبلت ۱۰ اینچ یومیو مدل S24",
    image_url: "https://example.test/a.jpg",
    tracking_link: "https://aflo.ir/abc",
    price: 10_000_000,
    price_discount: 0,
    discount_percent: 0,
    ...over,
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
  } as any;
}

describe("تخفیف غیرواقعی باور نمی‌شود", () => {
  test("درصد از خود قیمت‌ها حساب می‌شود، نه از فیلد افیلیو", () => {
    /*
      همان حالتی که روی سایت زنده دیده شد: افیلیو درصدی زیر سقف گزارش
      می‌کند ولی نسبت واقعی قیمت‌ها ۹۷٪ است.

      نسخه‌ی قبلی این را باور می‌کرد چون فقط `discount_percent` را
      می‌سنجید.
    */
    const product = toProduct(
      raw({ price: 10_000_000, price_discount: 310_000, discount_percent: 45 }),
      SOURCE,
    );

    assert.ok(product);
    assert.equal(
      product!.currentPrice,
      10_000_000,
      "قیمت ۳۱۰٬۰۰۰ روی تبلتی که فروشنده ۱۰ میلیون گفته، تخفیف نیست",
    );
  });

  test("تخفیف باورپذیر همچنان اعمال می‌شود", () => {
    // بدون این، اصلاح بالا هر تخفیف واقعی را هم دور می‌ریخت
    const product = toProduct(
      raw({ price: 10_000_000, price_discount: 7_000_000, discount_percent: 0 }),
      SOURCE,
    );

    assert.equal(product!.currentPrice, 7_000_000);
  });

  test("درصدِ گزارش‌شده‌ی بالا هم رد می‌شود", () => {
    const product = toProduct(
      raw({ price: 10_000_000, price_discount: 200_000, discount_percent: 98 }),
      SOURCE,
    );

    assert.equal(product!.currentPrice, 10_000_000);
  });
});

describe("محصول تازه ادعای «افت قیمت» نمی‌کند", () => {
  test("قیمت قبلی برابر قیمت امروز است", () => {
    /*
      `raw.price` تخفیف فروشگاه است، نه چیزی که ما ثبت کرده باشیم.
      تا وقتی تاریخچه‌ای نداریم، درست‌ترین حرف «نمی‌دانیم» است.
    */
    const product = toProduct(
      raw({ price: 10_000_000, price_discount: 7_000_000 }),
      SOURCE,
    );

    assert.equal(
      product!.previousPrice,
      product!.currentPrice,
      "محصولی که یک بار دیده‌ایم نباید در فهرست «بیشترین افت» بیاید",
    );
  });

  test("پنل پیشنهادها فقط از افت واقعی حرف می‌زند", () => {
    /*
      `buildSuggestions` محصولاتی را «ارزان‌تر شده» می‌خواند که
      `currentPrice < previousPrice` باشند. حالا که قیمت قبلی فقط از
      تاریخچه‌ی خودمان می‌آید، این شرط دیگر تخفیف فروشگاه را نمی‌شمارد.

      این تست همان زنجیره را قفل می‌کند: اگر کسی روزی `previousPrice` را
      دوباره از فید پر کند، «۷۵٪ کمتر» به صفحه‌ی اصلی برمی‌گردد.
    */
    const derived = read("src/lib/derived.ts");
    assert.ok(
      derived.includes("p.currentPrice < p.previousPrice"),
      "شرط افت قیمت عوض شده — این تست باید بازبینی شود",
    );

    const affilio = read("src/lib/affilio.ts");
    assert.ok(
      !/previousPrice:\s*raw\.price\b/.test(affilio),
      "قیمت قبلی دوباره از فید افیلیو پر می‌شود",
    );
  });
});

describe("دو ربات روی یک صفحه همدیگر را خراب نمی‌کنند", () => {
  const src = read("src/components/hero/RobotMascot.tsx");

  test("شناسه‌ی گرادیان‌ها ثابت نیست", () => {
    /*
      با `id="eyeGlow"` ثابت، دو نمونه‌ی ربات روی صفحه‌ی اصلی یک شناسه
      داشتند. `url(#eyeGlow)` به اولی اشاره می‌کند و اولی روی دسکتاپ
      همان ربات موبایلیِ `display:none` است — که مرورگر گرادیانش را
      رنگ‌آمیزی نمی‌کند.

      نتیجه: ربات دسکتاپ بدون چشم و صورت رندر می‌شد، بدون هیچ خطایی.
    */
    assert.ok(src.includes("useId"), "شناسه باید برای هر نمونه یکتا باشد");
    assert.ok(
      !/id="(botFace|eyeGlow)"/.test(src),
      "شناسه‌ی ثابت برگشته — با دو ربات روی یک صفحه دوباره می‌شکند",
    );
    assert.ok(
      !/url\(#(botFace|eyeGlow)\)/.test(src),
      "ارجاع به شناسه‌ی ثابت برگشته",
    );
  });
});

describe("نوار پایین روی موبایل ثابت نیست، در جریان عادی است", () => {
  /*
    کامنت‌ها پاک می‌شوند، وگرنه تست چیزی را می‌سنجد که فقط دربارهٔ کد
    *حرف* می‌زند.

    هر دو تست این بلوک اول قرمز شدند و هیچ‌کدام به‌خاطر کد نبود: یکی
    واژه‌ی `visualViewport` را داخل توضیحِ «چرا حذفش کردیم» پیدا کرد، و
    دیگری چون یک کامنت فارسی بلند بین سلکتور و خاصیت نشسته بود و از
    سقف کاراکتر رد شده بود.
  */
  const stripCss = (s: string) => s.replace(/\/\*[\s\S]*?\*\//g, "");
  const stripTs = (s: string) =>
    s.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");

  const css = stripCss(read("src/styles/globals.css"));
  const src = stripTs(read("src/components/layout/MobileTabBar.tsx"));

  /*
    ─────────────────────────────────────────────────────────────────────
    چرا معماری عوض شد
    ─────────────────────────────────────────────────────────────────────
    سه تلاش برای چسباندن این نوار با `position: fixed` شکست خورد. تلاش
    سوم بود که جواب را داد: لایه‌ی هم‌رنگ زیر نوار روی سرور زنده کاملاً
    درست محاسبه می‌شد — `323.5px | rgb(15,17,16) | top: 100%` — و باز
    روی گوشی چیزی نمی‌کشید.

    یعنی زیر زوم، سافاری iOS رسمِ المان ثابت را به viewport چیدمانی
    می‌برد و کاربر ناحیه‌ی بزرگ‌تری می‌بیند. هیچ چیزی *داخل* آن المان
    به آن ناحیه نمی‌رسد.

    راه‌حل پوشاندن نبود؛ این بود که آنجا محتوایی نباشد. حالا محتوا داخل
    `.psyg-scroller` اسکرول می‌کند و سند دقیقاً به اندازه‌ی صفحه است —
    همان ساختاری که دیجی‌کالا دارد.
  */

  test("پوسته‌ی اسکرول فقط روی موبایل فعال است", () => {
    /*
      روی دسکتاپ سند باید مثل قبل اسکرول کند، وگرنه اسکرول نرم Lenis
      می‌شکند. Lenis روی لمسی از قبل خاموش است، پس زیر lg تداخلی نیست.
    */
    assert.match(
      css,
      /@media \(width < 64rem\)[\s\S]{0,600}\.psyg-scroller/,
      "پوسته‌ی اسکرول باید پشت نقطه‌ی شکست باشد",
    );
  });

  test("نوار زیر موبایل از جریان ثابت درمی‌آید", () => {
    const shell = css.match(/@media \(width < 64rem\)[\s\S]*?\n\}/)?.[0] ?? "";
    assert.ok(shell, "بلوک پوسته‌ی موبایل پیدا نشد");
    assert.match(
      shell,
      /\.psyg-tabbar\s*\{[^}]*position:\s*relative/,
      "اگر نوار روی موبایل `fixed` بماند، همان باگ برمی‌گردد",
    );
  });

  test("ظرف اسکرول می‌تواند کوچک شود", () => {
    /*
      بدون `min-height: 0` یک فرزند فلکس کوچک‌تر از محتوایش نمی‌شود،
      پس `overflow-y: auto` هیچ‌وقت فعال نمی‌شود و کل صفحه — که حالا
      `overflow: hidden` است — غیرقابل اسکرول می‌ماند.

      این بدترین حالت ممکن است: محتوا هست ولی کاربر به آن نمی‌رسد.
    */
    const shell = css.match(/@media \(width < 64rem\)[\s\S]*?\n\}/)?.[0] ?? "";
    assert.match(shell, /\.psyg-scroller\s*\{[^}]*min-height:\s*0/);
    assert.match(shell, /\.psyg-scroller\s*\{[^}]*overflow-y:\s*auto/);
  });

  test("کد مرده‌ی visualViewport پاک شده", () => {
    /*
      آن هوک با این ساختار هیچ کاری نمی‌کند. کد بی‌اثری که تست نگهش
      دارد، بدتر از نبودنش است: دفعه‌ی بعد کسی وقت می‌گذارد بفهمد چرا
      اثری ندارد.
    */
    assert.ok(
      !src.includes("visualViewport"),
      "هوک بی‌اثر برگشته — یا حذفش کن یا توضیح بده چه کار می‌کند",
    );
  });

  test("ادامه‌ی هم‌رنگ زیرش کشیده می‌شود", () => {
    /*
      روی سافاری iOS، `bottom: 0` به viewport چیدمانی می‌چسبد که پشت
      نوار مرورگر ادامه دارد. نتیجه‌اش نواری از محتوای صفحه بود که از
      زیر نوار ما بیرون می‌زد.

      این لایه هیچ‌وقت چیزی را جابه‌جا نمی‌کند — برخلاف
      `env(safe-area-inset-bottom)` که پدینگ داخل نوار اضافه می‌کرد و
      خودش شکاف سیاه می‌ساخت.
    */
    const css = read("src/styles/globals.css");
    const rule = css.match(/\.psyg-tabbar::after\s*\{[\s\S]*?\n\}/)?.[0] ?? "";

    assert.ok(rule, "ادامه‌ی زیر نوار پایین حذف شده");
    assert.match(rule, /top:\s*100%/);
    assert.match(
      rule,
      /pointer-events:\s*none/,
      "بدون این، لایه لمس‌های نزدیک لبه را می‌بلعد",
    );

    /*
      رنگ باید صریح باشد، نه ارثی.

      نسخه‌ی `background: inherit` در کروم درست محاسبه می‌شد ولی روی
      گوشی چیزی نکشید. وقتی مقدار معلوم است، ارث بردنش فقط یک حلقه‌ی
      اضافه در زنجیره است که می‌تواند بشکند.
    */
    assert.match(
      rule,
      /background-color:\s*var\(--color-surface\)/,
      "رنگ باید صریح باشد تا روی همه‌ی مرورگرها کشیده شود",
    );

    /*
      ارتفاع باید نسبی باشد نه عددی حدسی.

      ۸۰ پیکسلِ نسخه‌ی قبلی از روی حدس آمده بود و اندازه‌گیری روی گوشی
      نشان داد نوار سافاری حدود ۸۳ پیکسل را می‌پوشاند — یعنی درست
      همان‌قدر کم می‌آورد که یک نوار باریک از محتوا دیده شود.
    */
    assert.match(
      rule,
      /height:\s*\d+vh/,
      "ارتفاع ثابت روی دستگاهی با نوار مرورگر بلندتر کم می‌آورد",
    );
  });
});
