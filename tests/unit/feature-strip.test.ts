import { strict as assert } from "node:assert";
import { test } from "node:test";
import { readFileSync } from "node:fs";

const source = readFileSync("src/components/marketing/FeatureStrip.tsx", "utf8");

/** بدون کامنت‌ها — وگرنه توضیحِ چرایی با خود کد اشتباه گرفته می‌شود */
const code = source
  .replace(/\{\/\*[\s\S]*?\*\/\}/g, "")
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/\/\/.*$/gm, "");

/**
 * نوار ویژگی‌ها.
 *
 * ─────────────────────────────────────────────────────────────────────
 * چرا این تست وجود دارد
 * ─────────────────────────────────────────────────────────────────────
 * `flex-row-reverse` بدون قید بریک‌پوینت، روی دسکتاپ درست دیده می‌شد و
 * روی موبایل خراب: آیکون به لبه‌ی چپ پرتاب می‌شد و از عنوانش جدا
 * می‌افتاد.
 *
 * این همان الگویی است که در این پروژه بارها تکرار شده — قاعده‌ای که در
 * یک عرض درست است و در عرض دیگر نه، و چون هر دو در یک فایل‌اند، کسی
 * موقع تغییر یکی به آن یکی فکر نمی‌کند.
 */

test("ترتیب معکوس فقط از xl به بعد اعمال می‌شود", () => {
  assert.match(code, /xl:flex-row-reverse/, "چیدمان دسکتاپ برداشته شده");

  /*
    نکته‌ی اصلی: هیچ `flex-row-reverse` بدون پیشوند بریک‌پوینت نباید
    بماند، وگرنه از موبایل هم اعمال می‌شود.
  */
  assert.doesNotMatch(
    code,
    /(?<![:\w-])flex-row-reverse/,
    "flex-row-reverse بدون قید بریک‌پوینت روی موبایل هم اعمال می‌شود",
  );
});

test("بلوک متن فضای باقی‌مانده را می‌گیرد", () => {
  /*
    بدون `flex-1`، بلوک متن به اندازه‌ی محتوایش عرض می‌گیرد و عنوان و
    توضیح روی دو عرض متفاوت می‌نشینند.
  */
  assert.match(code, /flex min-w-0 flex-1 flex-col/, "بلوک متن flex-1 ندارد");
});

test("آیکون در هیچ عرضی فشرده نمی‌شود", () => {
  assert.match(code, /size-12 shrink-0/, "آیکون بدون shrink-0 در عرض کم له می‌شود");
});

test("خودِ تست سالم است", () => {
  /*
    اگر حذف کامنت‌ها کار نکند، این تست ممکن است روی متن توضیح قرمز یا
    سبز شود — نه روی کد.
  */
  const stripped = "/* flex-row-reverse در توضیح */\nconst a = 1;"
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\/\/.*$/gm, "");
  assert.doesNotMatch(stripped, /flex-row-reverse/, "حذف کامنت کار نمی‌کند");
});
