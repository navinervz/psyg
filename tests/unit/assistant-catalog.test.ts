import test, { describe } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { products } from "@/lib/data";
import { categories } from "@/lib/reference";

const ROOT = join(import.meta.dirname, "..", "..");
const read = (p: string) => readFileSync(join(ROOT, p), "utf8");

/*
  ─────────────────────────────────────────────────────────────────────
  چرا این فایل وجود دارد
  ─────────────────────────────────────────────────────────────────────
  روی سایت زنده، مشاور خرید گفت:

    «لپ‌تاپ مخصوص بازی نداریم.»

  در حالی که همان لحظه در صفحه‌ی دسته‌ی لپ‌تاپ این محصول بود:

    «لپ تاپ ۱۵.۶ اینچ مخصوص بازی اچ پی مدل Victus 15 Core i5 13420H»

  علتش نه مدل بود نه پرامپت. سایت فقط ۶۰ محصول از ۸۰ را می‌فرستاد و
  مرتب‌سازی بر اساس افت قیمت بود — که چون هیچ محصولی افت ثبت‌شده نداشت،
  همه‌ی مقادیر صفر بودند و برش عملاً تصادفی شد.

  بیست محصول بی‌صدا حذف شدند و یکی‌شان تنها لپ‌تاپ گیمینگ کاتالوگ بود.

  ─────────────────────────────────────────────────────────────────────
  چرا این بدترین نوع باگ است
  ─────────────────────────────────────────────────────────────────────
  مشاور *با اطمینان* چیزی را انکار کرد که وجود داشت. کاربر پاسخ روشن و
  قاطع گرفت و رفت. هیچ خطایی هیچ‌جا ثبت نشد.
*/

describe("مشاور همه‌ی کاتالوگ را می‌بیند", () => {
  const route = read("src/app/api/assistant/route.ts");

  test("سقف از تعداد محصولات بزرگ‌تر است", () => {
    const cap = Number(route.match(/MAX_CATALOG = (\d+)/)?.[1]);
    assert.ok(cap, "سقف کاتالوگ پیدا نشد");

    assert.ok(
      cap >= products.length,
      `کاتالوگ ${products.length} محصول دارد ولی فقط ${cap} تا به مشاور می‌رسد — ` +
        `بقیه برای مشاور وجود ندارند و «نداریم» می‌گوید`,
    );
  });

  test("انتخاب نوبتی است، نه صرفاً مرتب‌سازی", () => {
    /*
      اگر روزی کاتالوگ از سقف بزرگ‌تر شود، برش نباید یک دسته‌ی کامل را
      حذف کند. انتخاب نوبتی تضمین می‌کند تا وقتی سقف پر نشده، هر دسته
      لااقل یک نماینده دارد.
    */
    assert.match(
      route,
      /byCategory/,
      "انتخاب باید دسته‌به‌دسته باشد تا برش یک دسته را کامل حذف نکند",
    );
    assert.ok(
      !/\.sort\([\s\S]{0,200}\.slice\(0, MAX_CATALOG\)/.test(route),
      "مرتب‌سازی ساده و برش، همان باگی است که لپ‌تاپ گیمینگ را حذف کرد",
    );
  });
});

describe("هیچ دسته‌ای از دید مشاور غایب نیست", () => {
  test("هر دسته‌ای که محصول دارد، در انتخاب هم هست", () => {
    /*
      این تست منطق واقعی را اجرا نمی‌کند (روت سروری است) ولی همان
      ضمانت را روی داده می‌سنجد: با سقف فعلی، هیچ دسته‌ای نباید خالی
      بماند.
    */
    const cap = Number(
      read("src/app/api/assistant/route.ts").match(/MAX_CATALOG = (\d+)/)?.[1],
    );

    const populated = categories
      .map((c) => ({
        id: c.id,
        n: products.filter((p) => p.category === c.id).length,
      }))
      .filter((c) => c.n > 0);

    assert.ok(populated.length > 0, "هیچ دسته‌ای محصول ندارد");

    /*
      با انتخاب نوبتی، هر دسته در دور اول یک نماینده می‌گیرد. پس تنها
      حالتی که دسته‌ای جا می‌ماند، این است که سقف از تعداد دسته‌ها هم
      کمتر باشد.
    */
    assert.ok(
      cap >= populated.length,
      `${populated.length} دسته‌ی پرشده داریم ولی سقف ${cap} است`,
    );
  });
});
