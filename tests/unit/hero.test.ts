import test, { describe } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..", "..");
const read = (p: string) => readFileSync(join(ROOT, p), "utf8");

const code = (src: string) =>
  src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");

/*
  ─────────────────────────────────────────────────────────────────────
  چرا این فایل وجود دارد
  ─────────────────────────────────────────────────────────────────────
  صفحه‌ی اصلی دو هیرو دارد: `MobileHero` و `HeroSection`. جدا کردنشان
  تصمیم درستی بود — دو چیدمان واقعاً متفاوت‌اند، نه یک چیدمان در دو
  اندازه.

  ولی یک خطر ساخت که بلافاصله اتفاق افتاد: دکمه‌ی «شکار فرصت‌ها» به
  نسخه‌ی موبایل اضافه شد و نسخه‌ی دسکتاپ بدون آن ماند. یعنی کاربر
  دسکتاپ بعد از خواندن هیرو هیچ مسیر مشخصی نداشت.

  هیچ خطایی تولید نشد و هیچ تستی قرمز نشد. فقط یک نفر روی دسکتاپ نگاه
  کرد و گفت «این دکمه اینجا نیست».

  این تست‌ها همان جاافتادگی را می‌گیرند.
*/

const MOBILE = "src/components/mobile/MobileHero.tsx";
const DESKTOP_COPY = "src/components/hero/HeroCopy.tsx";

describe("هر دو هیرو مسیر یکسانی به فرصت‌ها می‌دهند", () => {
  test("هر دو دکمه‌ی «شکار فرصت‌ها» دارند", () => {
    for (const path of [MOBILE, DESKTOP_COPY]) {
      const src = code(read(path));
      assert.ok(
        src.includes("شکار فرصت‌ها"),
        `${path} دکمه‌ی اصلی هیرو را ندارد`,
      );
    }
  });

  test("هر دو به همان مسیر می‌روند", () => {
    /*
      دو دکمه با یک متن که به دو جای متفاوت بروند، بدتر از نبودن یکی
      از آن‌هاست: کاربر موبایل و دسکتاپ تجربه‌ی متفاوتی می‌گیرند بدون
      اینکه کسی متوجه شود.
    */
    for (const path of [MOBILE, DESKTOP_COPY]) {
      const src = code(read(path));
      assert.match(
        src,
        /href="\/deals"/,
        `${path} دکمه‌اش به فرصت‌ها نمی‌رود`,
      );
    }
  });
});

describe("پیام هیرو همان چیزی است که تصمیم گرفتیم", () => {
  const copy = code(read(DESKTOP_COPY));

  test("سؤال بلاغی قدیمی برنگشته", () => {
    /*
      «دنبال بهترین فرصت خرید هستی؟» خوش‌آهنگ بود ولی بعد از خواندنش
      کاربر هنوز نمی‌دانست این سایت چه کار می‌کند.
    */
    assert.ok(
      !copy.includes("دنبال بهترین"),
      "تیتر سؤالی قدیمی برگشته",
    );
  });

  test("تیتر می‌گوید چه کاری انجام می‌شود", () => {
    for (const phrase of ["بررسی می‌کنه", "قبل از اینکه تموم بشن"]) {
      assert.ok(copy.includes(phrase), `عبارت «${phrase}» از تیتر افتاده`);
    }
  });

  test("«موندنی نیستن» سبز است و «فرصت‌ها» سفید", () => {
    /*
      رنگ اینجا تزئین نیست: «فرصت‌ها» موضوع جمله است و «موندنی نیستن»
      دلیلی که کاربر باید همین حالا نگاه کند. اگر هر دو یک رنگ شوند،
      جمله تأکیدش را از دست می‌دهد.

      متن حالا از `HERO_HEADLINE` می‌آید نه از رشته‌ی درون فایل، پس
      تست باید نگاشتِ بخش به رنگ را بسنجد، نه خود کلمه‌ها.

      نسخه‌ی اول همین تست بعد از جدا شدن متن قرمز شد — قاعده نشکسته
      بود، تست جای اشتباهی را نگاه می‌کرد.
    */
    for (const path of [MOBILE, DESKTOP_COPY]) {
      const src = code(read(path));
      assert.match(
        src,
        /text-hi[^>]*>\{HERO_HEADLINE\.lead\}/,
        `${path}: بخش اول باید رنگ متن اصلی را داشته باشد`,
      );
      assert.match(
        src,
        /text-accent[^>]*>\{HERO_HEADLINE\.accent\}/,
        `${path}: بخش دوم باید سبز باشد`,
      );
    }

    // و خودِ متن باید همان چیزی باشد که تصمیم گرفتیم
    const site = read("src/lib/site.ts");
    assert.match(site, /accent:\s*"موندنی نیستن"/);
  });
});

describe("صفحه‌ی اصلی فقط یک تیتر اصلی دارد", () => {
  /*
    ─────────────────────────────────────────────────────────────────────
    چرا این تست وجود دارد
    ─────────────────────────────────────────────────────────────────────
    دو هیرو داریم و هر دو همیشه در DOM هستند — یکی با `lg:hidden` پنهان
    می‌شود و دیگری با `hidden lg:block`. وقتی هر دو `<h1>` داشتند،
    صفحه‌ی اصلی دو تیتر اصلی داشت.

    این را روی سایت زنده پیدا کردیم، نه در تست: شمردن `<h1>` در HTML
    صفحه دو تا داد. تست e2e فقط پنج مسیر دیگر را می‌سنجید و `/` را نه.

    حالا تیتر واقعی یک بار در `page.tsx` است و هر دو هیرو با `<p>` همان
    متن را نشان می‌دهند.
  */
  test("هیچ‌کدام از دو هیرو h1 ندارند", () => {
    for (const path of [MOBILE, DESKTOP_COPY]) {
      const src = code(read(path));
      assert.ok(
        !/<h1[\s>]/.test(src),
        `${path} یک h1 دارد — تیتر اصلی باید فقط در page.tsx باشد`,
      );
    }
  });

  test("صفحه‌ی اصلی دقیقاً یک h1 دارد", () => {
    const page = code(read("src/app/page.tsx"));
    const count = (page.match(/<h1[\s>]/g) || []).length;
    assert.equal(count, 1, `صفحه‌ی اصلی ${count} تیتر اصلی دارد`);
  });

  test("متن تیتر از یک منبع می‌آید", () => {
    /*
      سه جا همین جمله را نشان می‌دهند. اگر هرکدام رشته‌ی خودش را داشته
      باشد، دیر یا زود از هم جدا می‌افتند و کاربر روی موبایل چیزی
      می‌بیند که با تیترِ گوگل فرق دارد.
    */
    for (const path of [MOBILE, DESKTOP_COPY, "src/app/page.tsx"]) {
      const src = code(read(path));
      assert.match(
        src,
        /HERO_HEADLINE/,
        `${path} متن تیتر را از منبع مشترک نمی‌خواند`,
      );
    }
  });
});

describe("رادار یک رادار است، نه چند برچسب متحرک", () => {
  const src = code(read("src/components/hero/RobotMascot.tsx"));

  test("بلیپ‌ها با عبور پرتو هماهنگ‌اند", () => {
    /*
      این تنها چیزی است که یک رادار را از «یک دایره‌ی متحرک و چند
      برچسب بی‌ربط» جدا می‌کند — که دقیقاً بازخورد نسخه‌ی قبلی بود.

      تأخیر هر بلیپ باید از زاویه‌اش حساب شود، نه دستی. اگر کسی عدد
      ثابت بگذارد، هماهنگی بی‌صدا از بین می‌رود.
    */
    assert.match(
      src,
      /delay:\s*\(blip\.angle \/ 360\)\s*\*\s*SWEEP_SECONDS/,
      "زمان‌بندی بلیپ باید از زاویه‌اش بیاید",
    );
  });

  test("صفحه‌ی رادار ثابت است و فقط پرتو می‌چرخد", () => {
    /*
      نسخه‌ی قبلی حلقه‌ها را هم می‌چرخاند. در رادار واقعی صفحه ثابت
      است؛ چرخاندنش نگاه را از پرتو می‌دزدد.
    */
    assert.ok(
      !/\.radar-grid[\s\S]{0,200}rotation/.test(src),
      "حلقه‌های رادار نباید بچرخند",
    );
    assert.match(src, /\.radar-sweep[\s\S]{0,120}rotation:\s*360/);
  });

  test("چرخش حول مرکز رادار است نه مرکز جعبه‌ی المان", () => {
    /*
      `transformOrigin` درصدی در SVG نسبت به جعبه‌ی خودِ المان حساب
      می‌شود و گوه دور نقطه‌ی اشتباهی می‌چرخید. `svgOrigin` مختصات را
      در فضای `viewBox` می‌خواند.
    */
    assert.match(src, /svgOrigin:\s*`\$\{CX\} \$\{CY\}`/);
  });

  test("بلیپ‌ها بیرون از خود ربات می‌نشینند", () => {
    /*
      نسخه‌ی اول مختصات دستی داشت و یکی از برچسب‌ها روی گوش ربات
      نشست. حالا شعاع تعیین‌کننده است.

      نیم‌قطر ربات تا نوک آنتن‌ها حدود ۱۰۲ و تا گوشه‌ها حدود ۱۴۰ است؛
      ۱۲۰ کف امنی است که برچسب روی صورت یا بدنه نیفتد.
    */
    const radii = [...src.matchAll(/radius:\s*(\d+)/g)].map((m) => Number(m[1]));
    assert.ok(radii.length >= 4, "بلیپ‌ها پیدا نشدند");

    for (const r of radii) {
      assert.ok(r >= 120, `شعاع ${r} خیلی کوچک است — برچسب روی ربات می‌افتد`);
    }
  });

  test("در حالت حرکت کم، رادار خالی نمی‌ماند", () => {
    /*
      بلیپ‌ها در نشانه‌گذاری `opacity="0"` هستند چون انیمیشن روشنشان
      می‌کند. بدون یک حالت ایستا، کاربری که حرکت کمتر خواسته صفحه‌ی
      رادار خالی می‌دید.
    */
    assert.match(
      src,
      /prefersReducedMotion\(\)\)\s*\{[\s\S]{0,600}radar-blip/,
      "حالت حرکت کم باید بلیپ‌ها را ایستا نشان بدهد",
    );
  });
});
