import test, { describe } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * محافظ دستیار خرید.
 *
 * ─────────────────────────────────────────────────────────────────────
 * چرا این تست وجود دارد
 * ─────────────────────────────────────────────────────────────────────
 * دستیار تنها جایی در سایت است که متنش را یک مدل زبانی می‌نویسد. همه‌ی
 * صفحات دیگر از `catalog.json` رندر می‌شوند و نمی‌توانند چیزی بگویند که
 * در داده نیست. دستیار می‌تواند.
 *
 * دو خطر مشخص:
 *
 * ۱. مدل محصولی را پیشنهاد دهد که روی سایت نیست. کاربر کلیک می‌کند و به
 *    ۴۰۴ می‌رسد — بدترین حالت ممکن برای سایتی که ادعای «دیتای واقعی»
 *    دارد.
 * ۲. مدل قیمت را داخل متن بنویسد. مدل‌های زبانی عدد را اشتباه بازنویسی
 *    می‌کنند و آن‌وقت حرف دستیار با صفحه‌ی محصول نمی‌خواند.
 *
 * هر دو با یک قاعده مهار شده‌اند: مدل فقط `slug` انتخاب می‌کند و سرور از
 * روی کاتالوگ واقعی پرش می‌کند. این تست‌ها آن قاعده را قفل می‌کنند.
 */

const ROOT = process.cwd();
const ROUTE = readFileSync(
  join(ROOT, "src", "app", "api", "assistant", "route.ts"),
  "utf8",
);
/*
  ─────────────────────────────────────────────────────────────────────
  چرا رابط کاربری از چند فایل خوانده می‌شود
  ─────────────────────────────────────────────────────────────────────
  دستیار قبلاً یک کامپوننت بود: `Assistant.tsx` — دکمه‌ی شناور گوشه‌ی
  صفحه با پنل و فیلد ورودی مستقل خودش.

  حالا سه تکه است: منطق در `useAssistantChat`، نمایش در `ChatPanel`، و
  ورودی همان فیلد جستجوی بالای صفحه.

  این تست‌ها به «کدام فایل» کاری ندارند؛ قاعده‌هایی را نگه می‌دارند که
  باید *جایی* رعایت شوند. پس همه‌ی فایل‌های دخیل با هم خوانده می‌شوند و
  اگر روزی معماری دوباره عوض شد، فقط همین فهرست به‌روز می‌شود.
*/
const UI = [
  "src/components/chat/ChatPanel.tsx",
  "src/components/chat/useAssistantChat.ts",
  "src/components/hero/AiSearchBar.tsx",
  "src/components/ui/Input.tsx",
]
  .map((file) => readFileSync(join(ROOT, file), "utf8"))
  .join("\n");

describe("دستیار خرید — پیشنهادها", () => {
  test("هر پیشنهاد قبل از نمایش با کاتالوگ واقعی تطبیق داده می‌شود", () => {
    /*
      `hydrate` محصول را در `products` پیدا می‌کند و اگر نبود `null`
      برمی‌گرداند. این تنها راهی است که یک پیشنهاد به کلاینت می‌رسد.
    */
    assert.match(
      ROUTE,
      /products\.find\(\s*\(p\)\s*=>\s*p\.slug === pick\.slug\s*\)/,
      "پیشنهاد باید در کاتالوگ واقعی جستجو شود",
    );
    assert.match(
      ROUTE,
      /if \(!product\) return null/,
      "محصول ناموجود باید حذف شود، نه اینکه با داده‌ی ناقص نمایش داده شود",
    );
    assert.match(
      ROUTE,
      /\.filter\(\(p\): p is HydratedPick => p !== null\)/,
      "پیشنهادهای رد شده باید از خروجی فیلتر شوند",
    );
  });

  test("قیمت از کاتالوگ می‌آید، نه از متن مدل", () => {
    assert.match(
      ROUTE,
      /currentPrice: product\.currentPrice/,
      "قیمت باید از شیء محصول خوانده شود",
    );
    // `pick` تنها باید `slug` و `why` بدهد — هیچ فیلد عددی از مدل پذیرفته نشود
    assert.match(
      ROUTE,
      /type Pick = \{ slug: string; why: string \}/,
      "شکل پاسخ مدل باید فقط شناسه و دلیل باشد؛ اضافه کردن فیلد عددی یعنی به عدد مدل اعتماد کرده‌ایم",
    );
  });

  test("وقتی دستیار در دسترس نیست، پاسخ ساختگی برنمی‌گرداند", () => {
    /*
      وسوسه‌ی برگرداندن یک جواب از پیش نوشته زیاد است، ولی کاربر فرقش را
      نمی‌فهمد و فکر می‌کند با هوش مصنوعی حرف می‌زند.
    */
    assert.match(
      ROUTE,
      /status: 503/,
      "نبود وبهوک باید ۵۰۳ بدهد نه جواب آماده",
    );
  });
});

describe("دستیار خرید — امنیت", () => {
  test("هیچ کلید هوش مصنوعی در کد سایت نیست", () => {
    /*
      کلیدها در n8n می‌مانند و سایت فقط یک وبهوک صدا می‌زند. اگر روزی کسی
      برای «ساده‌تر شدن» کلید را مستقیم اینجا بیاورد، این تست قرمز می‌شود.
    */
    for (const source of [ROUTE, UI]) {
      assert.doesNotMatch(
        source,
        /(OPENAI|ANTHROPIC|GEMINI|GROQ|MISTRAL|OPENROUTER)_API_KEY/,
        "کلید مدل نباید در سایت باشد — جایش n8n است",
      );
      assert.doesNotMatch(
        source,
        /sk-[A-Za-z0-9]{20}/,
        "کلید هاردکد شده در کد پیدا شد",
      );
    }
  });

  test("پیام کاربر پیش از ارسال محدود می‌شود", () => {
    assert.match(
      ROUTE,
      /MAX_MESSAGE_LENGTH/,
      "پیام باید سقف طول داشته باشد تا کسی نتواند پرامپت غول‌آسا بفرستد",
    );
    assert.match(
      ROUTE,
      /AbortSignal\.timeout/,
      "درخواست به n8n باید تایم‌اوت داشته باشد تا کاربر پشت اسپینر بی‌پایان نماند",
    );
  });
});

describe("دستیار خرید — رابط کاربری", () => {
  test("صراحتاً می‌گوید خرید در فروشگاه اصلی انجام می‌شود", () => {
    /*
      سای‌جی فروشگاه نیست. کاربری که فکر کند اینجا پول می‌دهد و بعد به
      دیجی‌کالا پرتاب شود، اعتمادش را از دست می‌دهد — و اعتماد تنها
      دارایی این سایت است.
    */
    assert.match(
      UI,
      /خرید در (خود )?فروشگاه/,
      "سبد باید صریح بگوید پرداخت اینجا نیست",
    );
  });

  test("لینک خروجی نشانه‌گذاری سئویی درست دارد", () => {
    assert.match(
      UI,
      /rel="nofollow sponsored noopener noreferrer"/,
      "لینک کمیسیونی بدون nofollow sponsored به سئو آسیب می‌زند",
    );
  });

  test("ورودی روی موبایل باعث زوم سافاری نمی‌شود", () => {
    /*
      سافاری iOS اگر فونت فیلد کمتر از ۱۶px باشد موقع فوکوس کل صفحه را
      زوم می‌کند و کاربر گیر می‌افتد.
    */
    /*
      فیلد ورودی حالا همان `Input` مشترک سایت است، نه یک فیلد اختصاصی
      داخل پنل دستیار. `text-base` در پایه‌ی ۱۸ پیکسلی این سایت بالای
      ۱۶ پیکسل می‌نشیند و `sm:text-sm` فقط از تبلت به بالا اعمال
      می‌شود — جایی که سافاری موبایل دیگر در کار نیست.
    */
    assert.match(
      UI,
      /text-base[\s\S]{0,40}sm:text-sm/,
      "فیلد ورودی باید روی موبایل حداقل ۱۶ پیکسل باشد",
    );
  });

  test("ارتفاع پنل با dvh گرفته می‌شود نه vh", () => {
    /*
      نوار آدرس مرورگر موبایل باز و بسته می‌شود؛ با `vh` فیلد ورودی زیر
      نوار گم می‌شد.
    */
    assert.match(UI, /dvh/, "ارتفاع باید dvh باشد");
    assert.doesNotMatch(
      UI,
      /h-\[min\(\d+px,\s*\d+vh\)\]/,
      "vh روی موبایل ارتفاع را اشتباه حساب می‌کند",
    );
  });
});
