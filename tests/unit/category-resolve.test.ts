import { strict as assert } from "node:assert";
import { test } from "node:test";
import { resolveCategory } from "@/lib/affilio";

/**
 * تنزل لوازم جانبی به دسته‌ی خودش.
 *
 * ─────────────────────────────────────────────────────────────────────
 * چرا این تست‌ها با عنوان‌های واقعی نوشته شده‌اند
 * ─────────────────────────────────────────────────────────────────────
 * هر عنوان این فایل از پاسخ زنده‌ی افیلیو کپی شده، نه از ذهن من. دلیلش
 * این است که خطای اصلی از یک *فرض* درباره‌ی داده آمد («هر ویجت دسته‌اش
 * خالص است») و فرض بعدی هم می‌تواند به همان شکل غلط باشد.
 *
 * خطرناک‌ترین حالت، گروه دوم است: گوشی و لپ‌تاپی که در عنوانشان «کاور»
 * و «محافظ صفحه نمایش» دارند چون فروشنده بسته‌ای می‌فروشد. جستجوی ساده
 * در کل متن، آن‌ها را هم لوازم جانبی می‌کرد — یعنی گران‌ترین محصولات
 * سایت از دسته‌ی خودشان حذف می‌شدند.
 */

test("کیف و روکش و پایه، لوازم جانبی می‌شوند نه کنسول", () => {
  const accessories = [
    "کیف حمل کنسول ps5 نهل مدل 30th anniversary",
    "کیف حمل ps5 fat نهل مدل ghost of tsushima",
    "روکش آنالوگ KontrolFreek طرح Vortex مناسب PS5/PS4",
    "پایه شارژ دسته بازی دابی مدل DualSense TP5-05",
    "نگهدارنده دسته بازی مدل مرد عنکبوتی",
    "کابل تبدیل کامپوننت به RCA مدل P2 مناسب برای پلی استیشن 2",
  ];

  for (const title of accessories) {
    assert.equal(
      resolveCategory(title, "console"),
      "accessory",
      `باید لوازم جانبی می‌شد: ${title}`,
    );
  }
});

test("محصولی که در عنوانش کاور همراه دارد، دسته‌اش حفظ می‌شود", () => {
  /*
    این دقیقاً همان تله است. اگر روزی کسی این را به «شامل شدن در کل
    عنوان» تغییر داد، این تست قرمز می‌شود و دلیلش را همین‌جا می‌خواند.
  */
  const bundled = [
    [
      "گوشی موبایل سامسونگ مدل Galaxy A37 دو سیم‌کارت ظرفیت 256 گیگابایت و رم 8 گیگابایت - ویتنام - به همراه یک عدد شارژر 45 وات سامسونگ، یک عدد کابل UBS-C به طول 1.8 متر، یک عدد کاور سیلیکونی و یک عدد محافظ صفحه نمایش",
      "mobile",
    ],
    [
      "گوشی موبایل شیائومی مدل Redmi Note 15 Pro 4G دو سیم کارت ظرفیت 256 گیگابایت و رم 8 گیگابایت - به همراه 2 عدد کاور و 2 عدد محافظ صفحه نمایش",
      "mobile",
    ],
    [
      "لپ تاپ 16 اینچی ایسوس مدل TUF Gaming F16 FX608JMR-F16I75060-i7 14650HX-32GB DDR5 5600MHz-1TB SSD-RTX5060 8GB-FHD 165Hz-W",
      "laptop",
    ],
    ["هدفون بی سیم پرووان کد PHB3307", "headphone"],
    ["هدفون مارشال مدل major IV", "headphone"],
  ] as const;

  for (const [title, expected] of bundled) {
    assert.equal(resolveCategory(title, expected), expected, `دسته عوض شد: ${title}`);
  }
});

test("نگاشت یک‌طرفه است — چیزی از لوازم جانبی بیرون نمی‌آید", () => {
  /*
    اگر ویجت لوازم جانبی روزی یک گوشی داشته باشد، همان‌جا می‌ماند.
    ارتقای خودکار یعنی یک کیف می‌تواند کنسول شود، و آن دقیقاً همان
    مشکلی است که این کد برای رفعش نوشته شده.
  */
  assert.equal(resolveCategory("گوشی موبایل اپل مدل iPhone 16", "accessory"), "accessory");
  assert.equal(resolveCategory("کیف حمل کنسول ps5", "accessory"), "accessory");
});

test("عنوان با نیم‌فاصله یا فاصله‌ی اضافه هم درست خوانده می‌شود", () => {
  assert.equal(resolveCategory("  کیف حمل کنسول ps5 slim", "console"), "accessory");
  assert.equal(resolveCategory("محافظ صفحه نمایش گوشی", "mobile"), "accessory");
});
