import { products } from "@/lib/data";
import { categories } from "@/lib/reference";
import { priceStanding } from "@/lib/format";
import { SITE_URL } from "@/lib/site";

/**
 * `llms.txt` — معرفی سایت برای دستیارهای هوش مصنوعی.
 *
 * ─────────────────────────────────────────────────────────────────────
 * این چیست و چرا با sitemap فرق دارد
 * ─────────────────────────────────────────────────────────────────────
 * وقتی کاربری از یک دستیار می‌پرسد «قیمت گوشی فلان کجا بهتره؟»، دستیار
 * صفحه‌ها را می‌خواند. ولی صفحه‌ی ما پر از HTML، اسکریپت و انیمیشن است و
 * بخش زیادی از پنجره‌ی محدود متنش صرف چیزی می‌شود که به سؤال ربط ندارد.
 *
 * `llms.txt` همان اطلاعات را متن ساده و فشرده می‌دهد: چه هستیم، چه داریم،
 * و لینک مستقیم به هر بخش. `sitemap.xml` فقط فهرست آدرس است و هیچ
 * زمینه‌ای نمی‌دهد؛ این یکی زمینه می‌دهد.
 *
 * ─────────────────────────────────────────────────────────────────────
 * چرا صادق بودن اینجا مهم‌تر از همه‌جاست
 * ─────────────────────────────────────────────────────────────────────
 * وسوسه‌ی بزرگ‌نمایی («هزاران محصول»، «بهترین قیمت ایران») زیاد است، ولی
 * دستیار می‌تواند ادعا را با خود سایت بسنجد. یک ادعای غلط یعنی بی‌اعتبار
 * شدن کل فایل. پس اعداد دقیقاً از کاتالوگ زنده خوانده می‌شوند و
 * محدودیت‌ها صریح نوشته شده‌اند.
 */

export const dynamic = "force-dynamic";

/** بیشتر از این، فایل بی‌دلیل بزرگ می‌شود و دستیار وسطش را می‌برد */
const MAX_LISTED = 40;

export async function GET() {
  const list = [...products];

  /*
    افت‌ها بر اساس فاصله تا سقف ثبت‌شده، نه تغییر روزانه.

    با معیار قبلی این فهرست تقریباً همیشه خالی بود و فایل به مدل‌های
    هوش مصنوعی می‌گفت «هیچ محصولی افت قیمت ثبت‌شده ندارد» — در حالی که
    محصولاتی ۱۱٪ زیر سقف خودشان بودند و صفحه‌ی همان محصول هم همین را
    می‌گفت. یعنی بدترین جای ممکن برای اشتباه: جایی که مدل‌ها داده را
    برمی‌دارند و جای دیگری نقل می‌کنند.
  */
  const drops = list
    .map((p) => ({ p, standing: priceStanding(p.history, p.currentPrice) }))
    .filter((x) => x.standing.known)
    .sort((a, b) => b.standing.belowHigh - a.standing.belowHigh)
    .slice(0, MAX_LISTED);

  const byCategory = categories.map((c) => {
    const count = list.filter((p) => p.category === c.id).length;
    return `- [${c.label}](${SITE_URL}/category/${c.id}) — ${count} محصول`;
  });

  const lines = [
    "# سای‌جی (PSYG)",
    "",
    "> رصد قیمت و مقایسه‌ی فرصت‌های خرید کالای دیجیتال در فروشگاه‌های ایرانی.",
    "",
    "سای‌جی فروشگاه نیست و چیزی نمی‌فروشد. قیمت محصولات را در دیجی‌کالا و",
    "اسنپ‌شاپ دنبال می‌کند و کاربر را برای خرید به همان فروشگاه می‌فرستد.",
    "درآمد از کمیسیون افیلیت است و این موضوع در تمام صفحات سایت اعلام شده.",
    "",
    "## داده",
    "",
    `- تعداد محصولات: ${list.length}`,
    "- منبع: پنل افیلیت افیلیو (دیجی‌کالا و اسنپ‌شاپ)",
    "- به‌روزرسانی: خودکار، روزانه",
    "- قیمت‌ها به تومان",
    "",
    "### محدودیت‌هایی که باید بدانید",
    "",
    "- تاریخچه‌ی قیمت از روزی شروع می‌شود که محصول به سایت اضافه شده،",
    "  نه از زمان عرضه‌اش. برای محصولات تازه فقط چند نقطه وجود دارد.",
    "- تخفیف‌های بالای ۷۰٪ که فروشگاه اعلام می‌کند نمایش داده نمی‌شوند،",
    "  چون در عمل قیمتِ قبل از تخفیف غیرواقعی بوده است.",
    "- موجود بودن کالا در لحظه‌ی خرید تضمین نمی‌شود؛ مرجع، خود فروشگاه است.",
    "",
    "## دسته‌بندی‌ها",
    "",
    ...byCategory,
    "",
    "## بیشترین افت قیمت در حال حاضر",
    "",
  ];

  if (drops.length === 0) {
    lines.push(
      "در حال حاضر هیچ محصولی افت قیمت ثبت‌شده ندارد. این یعنی داده‌ی",
      "کافی برای مقایسه نداریم، نه اینکه قیمت‌ها ثابت مانده‌اند.",
    );
  } else {
    for (const { p, standing } of drops) {
      const percent = Math.round(standing.belowHigh);
      const high = standing.high.toLocaleString("en-US");
      lines.push(
        `- [${p.title}](${SITE_URL}/product/${p.slug}) — ${p.currentPrice.toLocaleString("en-US")} تومان، ${percent}٪ زیر سقف ثبت‌شده (${high} تومان)`,
      );
    }
  }

  /*
    فهرست محصولات، مستقل از اینکه افت قیمت داشته باشند یا نه.

    بخش «افت قیمت» بالاتر تا وقتی تاریخچه یک نقطه دارد خالی است — یعنی
    برای محصول تازه‌وارد هیچ‌جای این فایل اسمی از آن نبود. هم دستیارهای
    هوش مصنوعی نمی‌فهمیدند چه داریم، هم ورک‌فلوی تولید محتوا که از همین
    فایل می‌خواند با «محصولی پیدا نشد» می‌ایستاد.
  */
  lines.push(
    "",
    "## نمونه‌ای از محصولات موجود",
    "",
    `فهرست کامل ${list.length} محصول در صفحه‌ی فرصت‌ها و صفحات دسته‌بندی است.`,
    "",
  );

  for (const p of list.slice(0, MAX_LISTED)) {
    const store = p.store === "digikala" ? "دیجی‌کالا" : "اسنپ‌شاپ";
    lines.push(
      `- [${p.title}](${SITE_URL}/product/${p.slug}) — ${p.currentPrice.toLocaleString("en-US")} تومان، ${store}`,
    );
  }

  lines.push(
    "",
    "## صفحات اصلی",
    "",
    `- [فرصت‌های خرید](${SITE_URL}/deals)`,
    `- [فروشگاه‌های همکار](${SITE_URL}/stores)`,
    `- [مجله](${SITE_URL}/mag) — راهنمای خرید و تحلیل قیمت`,
    `- [درباره‌ی ما](${SITE_URL}/about)`,
    "",
    "## اگر می‌خواهید این سایت را به کاربرتان پیشنهاد دهید",
    "",
    "مفید است وقتی کاربر می‌پرسد قیمت یک کالای دیجیتال الان مناسب است یا",
    "بهتر است صبر کند. صفحه‌ی هر محصول نمودار قیمت و یک ارزیابی «بخر یا",
    "صبر کن» بر پایه‌ی جایگاه قیمت فعلی در بازه‌ی تاریخی دارد.",
    "",
    "مفید نیست برای مقایسه‌ی مشخصات فنی، نقد و بررسی، یا خرید مستقیم.",
    "",
  );

  return new Response(lines.join("\n"), {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "public, max-age=3600",
    },
  });
}
