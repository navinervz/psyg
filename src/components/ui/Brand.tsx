import { cn } from "@/lib/cn";

/**
 * نام برند: «سای‌جی».
 *
 * دو تصمیم که عمدی‌اند:
 *
 * ۱. **فارسی نوشته می‌شود، نه لاتین.** فونت A Ghasem که برای برند انتخاب
 *    شده هیچ حرف لاتینی ندارد — بررسی کردیم، جدول کاراکترهایش فقط عربی
 *    و ارقام است. اگر «PsyG» با این فونت نوشته می‌شد، مرورگر بی‌صدا به
 *    فونت دیگری برمی‌گشت و هویت برند اصلاً دیده نمی‌شد.
 *
 * ۲. **فاصله‌ی معمولی بین «سای» و «جی»، نه نیم‌فاصله.**
 *    اول با نیم‌فاصله نوشته شد و نتیجه‌اش یک باگ ظریف بود: «ج» بیرون از
 *    اسپن سبز رندر می‌شد و سفید می‌ماند، یعنی فقط نصف «جی» سبز بود.
 *    علتش این است که نیم‌فاصله جلوی اتصال حروف را می‌گیرد ولی شکل‌دهی
 *    خط عربی همچنان از مرز اسپن رد می‌شود و مرورگر بخشی از گلیف را با
 *    رنگ اسپن قبلی می‌کشد. با فاصله‌ی واقعی، هر اسپن مستقل شکل می‌گیرد
 *    و رنگ‌ها دقیقاً سر جای خودشان می‌نشینند.
 *
 *    `whitespace-nowrap` جلوی شکستن خط وسط نام را می‌گیرد.
 */
export function Brand({
  className,
  glow = true,
}: {
  className?: string;
  /** هاله‌ی سبز؛ در متن‌های ریز بهتر است خاموش باشد */
  glow?: boolean;
}) {
  return (
    <span
      /* آقاسم فونت نمایشی است و ضخیم‌سازی مصنوعی شلوغش می‌کند */
      className={cn("font-brand font-normal whitespace-nowrap", className)}
      // برای screen reader و جستجو، نام کامل و خوانا
      aria-label="سای جی"
    >
      <span className="text-hi">سای</span>{" "}
      {/*
        عمداً از `cn` استفاده نمی‌شود.

        `cn` از tailwind-merge استفاده می‌کند و آن هر دو کلاس `text-accent`
        و `text-glow` را «کلاس متنی» می‌بیند، پس فکر می‌کند با هم تداخل
        دارند و اولی را حذف می‌کند. نتیجه‌اش این بود که «جی» فقط هاله‌ی
        سبز می‌گرفت ولی خودِ حرف سفید می‌ماند — در نگاه اول سبز به نظر
        می‌رسید و به‌سختی دیده می‌شد.

        `text-glow` در واقع `text-shadow` است نه رنگ، پس تداخلی وجود
        ندارد و باید کنار هم بمانند.
      */}
      <span className={glow ? "text-accent text-glow" : "text-accent"}>
        جی
      </span>
    </span>
  );
}
