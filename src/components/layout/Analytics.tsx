import Script from "next/script";

/**
 * گوگل آنالیتیکس.
 *
 * ─────────────────────────────────────────────────────────────────────
 * چرا `next/script` و نه تگ ساده
 * ─────────────────────────────────────────────────────────────────────
 * با `strategy="afterInteractive"` اسکریپت بعد از تعامل‌پذیر شدن صفحه
 * بارگذاری می‌شود، نه در مسیر بحرانی رندر. آنالیتیکس نباید سرعت سایتی
 * را کم کند که کل ارزشش سریع نشان دادن قیمت است.
 *
 * ─────────────────────────────────────────────────────────────────────
 * تنظیمات حریم خصوصی که پیش‌فرض نیستند
 * ─────────────────────────────────────────────────────────────────────
 * سه چیز عمداً تغییر داده شده:
 *
 * `anonymize_ip` — آخرین بخش نشانی آی‌پی پیش از ذخیره حذف می‌شود.
 * برای آمار بازدید هیچ فرقی نمی‌کند و داده‌ی شخصی کمتری از کاربر
 * بیرون می‌رود.
 *
 * `allow_google_signals: false` — جلوی اتصال رفتار کاربر به پروفایل
 * تبلیغاتی گوگل را می‌گیرد. ما تبلیغات هدفمند نمی‌فروشیم، پس دلیلی
 * برای دادن این داده نداریم.
 *
 * `allow_ad_personalization_signals: false` — همان منطق.
 *
 * این‌ها آماری را که واقعاً لازم داریم — چند نفر آمدند، از کجا، چه
 * صفحه‌ای دیدند — دست‌نخورده نگه می‌دارند.
 *
 * ─────────────────────────────────────────────────────────────────────
 * اگر شناسه ست نشده باشد
 * ─────────────────────────────────────────────────────────────────────
 * هیچ اسکریپتی بارگذاری نمی‌شود. یعنی محیط توسعه و تست هیچ داده‌ای به
 * گوگل نمی‌فرستند و آمار با بازدیدهای خودمان آلوده نمی‌شود.
 */
export function Analytics() {
  const id = process.env.NEXT_PUBLIC_GA_ID;

  if (!id) return null;

  return (
    <>
      <Script
        src={`https://www.googletagmanager.com/gtag/js?id=${id}`}
        strategy="afterInteractive"
      />
      <Script id="ga-init" strategy="afterInteractive">
        {`
          window.dataLayer = window.dataLayer || [];
          function gtag(){dataLayer.push(arguments);}
          gtag('js', new Date());
          gtag('config', '${id}', {
            anonymize_ip: true,
            allow_google_signals: false,
            allow_ad_personalization_signals: false
          });
        `}
      </Script>
    </>
  );
}
