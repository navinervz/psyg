"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { BookOpen, Home, Info, LayoutGrid, Search, Store } from "lucide-react";
import { NAV_LINKS } from "@/lib/nav";
import { cn } from "@/lib/cn";

/**
 * نوار پایین موبایل — قالب اپلیکیشن.
 *
 * ─────────────────────────────────────────────────────────────────────
 * چرا نوار پایین و نه فقط منوی همبرگری
 * ─────────────────────────────────────────────────────────────────────
 * بیشتر ترافیک این سایت موبایل است و کاربر ایرانی مسیرهای اصلی را
 * پایین صفحه انتظار دارد، جایی که شست می‌رسد. منوی همبرگری هنوز هست
 * ولی برای مسیرهای فرعی؛ این پنج تا همان‌هایی‌اند که مدام لازم می‌شوند.
 *
 * ─────────────────────────────────────────────────────────────────────
 * چرا `lg:hidden` و نه رندر شرطی در جاوااسکریپت
 * ─────────────────────────────────────────────────────────────────────
 * تشخیص موبایل با جاوااسکریپت یعنی سرور نمی‌داند چه بفرستد، و در اولین
 * فریم یا نوار پرش می‌کند یا نبودش دیده می‌شود. با کلاس CSS، سرور همان
 * HTML را می‌فرستد و مرورگر تصمیم می‌گیرد — بدون پرش.
 */

/*
  آیکون هر مسیر، جدا از خود مسیر.

  ─────────────────────────────────────────────────────────────────────
  چرا از NAV_LINKS می‌خواند و فهرست جدا ندارد
  ─────────────────────────────────────────────────────────────────────
  نسخه‌ی اول پنج مسیر خودش را داشت — خانه، دسته‌بندی، جستجو،
  علاقه‌مندی، حساب. برچسب‌ها از طرح گرفته شده بودند ولی مسیرها با
  منویی که حذف کردیم یکی نبودند.

  نتیجه‌اش این شد که فروشگاه‌ها، مجله و درباره‌ی ما فقط در فوتر ماندند
  و کاربر موبایل عملاً راه سریعی به آن‌ها نداشت.

  حالا نوار پایین همان مسیرهای منوست. یک منبع، یک فهرست — اگر روزی
  مسیری اضافه یا حذف شود، جای دیگری نیست که یادمان برود به‌روزش کنیم.
*/
const ICONS: Record<string, typeof Home> = {
  "/": Home,
  "/deals": LayoutGrid,
  "/stores": Store,
  "/mag": BookOpen,
  "/about": Info,
};

const FALLBACK_ICON = Search;

export function MobileTabBar() {
  const pathname = usePathname();

  return (
    <nav
      dir="rtl"
      aria-label="مسیرهای اصلی"
      /*
        ─────────────────────────────────────────────────────────────
        `fixed` اینجا فقط یک پایه است؛ روی موبایل بازنویسی می‌شود
        ─────────────────────────────────────────────────────────────
        در `globals.css` زیر ۱۰۲۴ پیکسل این نوار `position: relative`
        می‌شود و در جریان عادی، به‌عنوان آخرین فرزند بدنه می‌نشیند.
        محتوا داخل `.psyg-scroller` اسکرول می‌کند.

        سه تلاش قبلی برای چسباندن این نوار با `position: fixed` شکست
        خورد و هر بار درسی داشت:

        ۱. `env(safe-area-inset-bottom)` — روی آیفون همیشه ۳۴ پیکسل
           است، حتی وقتی نوار مرورگر همان ناحیه را پوشانده. خودش
           شکاف سیاه ساخت.
        ۲. گره زدن به `visualViewport` — منطقش درست بود ولی روی گوشی
           `شکاف = ۰` گزارش می‌کرد در حالی که کاربر شکاف را می‌دید.
           کد بی‌اثری بود که تست نگهش داشته بود؛ حذف شد.
        ۳. لایه‌ی هم‌رنگ زیر نوار — روی سرور زنده کاملاً درست محاسبه
           می‌شد (`323.5px | rgb(15,17,16) | top: 100%`) و باز چیزی
           نمی‌کشید. همین ثابت کرد که زیر زوم، هیچ چیزی *داخل* یک
           المان ثابت به ناحیه‌ی دیده‌شده نمی‌رسد.

        رنگ `bg-surface` است نه `bg-night`: تیره‌ی صفحه روی صفحه‌ی
        تیره عملاً نامرئی بود و نوار مثل چند آیکون شناور به‌نظر
        می‌رسید، نه یک سطح.
      */
      className="psyg-tabbar glass fixed inset-x-0 bottom-0 z-[60] border-t border-line lg:hidden"
    >
      <ul className="grid grid-cols-5">
        {NAV_LINKS.map((tab) => {
          /*
            `/` باید دقیق بخورد وگرنه همیشه فعال است. بقیه با پیشوند،
            تا مثلاً `/mag/some-article` هم «مجله» را روشن نگه دارد.
          */
          const active =
            tab.href === "/"
              ? pathname === "/"
              : pathname.startsWith(tab.href);

          const Icon = ICONS[tab.href] ?? FALLBACK_ICON;

          return (
            <li key={tab.href}>
              <Link
                href={tab.href}
                aria-current={active ? "page" : undefined}
                /*
                  ارتفاع ۵۶ پیکسل به‌علاوه‌ی عرض یک‌پنجم صفحه، هدف لمسی
                  را در هر گوشی‌ای بالای حداقل استاندارد نگه می‌دارد.
                */
                className={cn(
                  "flex h-[56px] flex-col items-center justify-center gap-1 transition-colors",
                  active ? "text-accent" : "text-low hover:text-mid",
                )}
              >
                <span
                  className={cn(
                    "grid size-7 place-items-center rounded-xl transition-colors",
                    active && "bg-accent/12",
                  )}
                >
                  <Icon className="size-[18px]" strokeWidth={active ? 2.4 : 1.9} />
                </span>
                <span className="text-[10px] font-semibold leading-none">
                  {tab.label}
                </span>
              </Link>
            </li>
          );
        })}
      </ul>
    </nav>
  );
}
