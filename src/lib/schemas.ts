import { z } from "zod";

export const subscribeSchema = z.object({
  email: z
    .string()
    .min(1, "ایمیلت رو وارد کن")
    .email("قالب ایمیل درست نیست"),
});

export type SubscribeInput = z.infer<typeof subscribeSchema>;

/**
 * فرم تماس.
 *
 * ─────────────────────────────────────────────────────────────────────
 * چرا سقف و کف طول
 * ─────────────────────────────────────────────────────────────────────
 * کف ده کاراکتر جلوی پیام‌های «سلام» و «تست» را می‌گیرد که فقط صندوق
 * ورودی را شلوغ می‌کنند. سقف دو هزار کاراکتر جلوی کسی را می‌گیرد که
 * می‌خواهد با یک درخواست، مگابایت‌ها متن به ایمیل ما بفرستد.
 *
 * `subject` اختیاری است چون اجباری کردنش فقط یک مانع دیگر بین کاربر و
 * گزارش دادن ایراد می‌گذارد — و ایراد گزارش‌نشده از ایراد بی‌عنوان بدتر
 * است.
 */
export const contactSchema = z.object({
  email: z
    .string()
    .min(1, "ایمیلت رو وارد کن")
    .email("قالب ایمیل درست نیست"),
  subject: z.string().trim().max(120, "عنوان خیلی بلند است").optional(),
  message: z
    .string()
    .trim()
    .min(10, "پیامت رو کمی کامل‌تر بنویس")
    .max(2000, "پیام خیلی بلند است؛ خلاصه‌ترش کن"),
  /*
    تله‌ی ربات.

    یک فیلد که برای کاربر نامرئی است و هیچ‌وقت پر نمی‌شود. ربات‌های فرم
    هر ورودی‌ای را که ببینند پر می‌کنند، پس پر بودنش یعنی ربات.

    ارزشش این است که هیچ هزینه‌ای برای کاربر واقعی ندارد — نه کپچا، نه
    کلیک اضافه.
  */
  website: z.string().max(0).optional(),
});

export type ContactInput = z.infer<typeof contactSchema>;
